function stitchGrid80(parts) {
  const grid = Array.from(
    { length: 80 },
    () => Array(80).fill(".")
  );

  for (const part of parts) {
    const [rowText, columnText, stitches] = part.split(":");
    const row = Number(rowText);
    const column = Number(columnText);

    if (
      !Number.isInteger(row) ||
      !Number.isInteger(column) ||
      row < 0 || row >= 80 ||
      column < 0 ||
      column + stitches.length > 80
    ) {
      throw new Error("Invalid embroidery row: " + part);
    }

    [...stitches].forEach((symbol, offset) => {
      grid[row][column + offset] = symbol;
    });
  }

  return grid.map(row => row.join(""));
}


