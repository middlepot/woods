let isStitching = false;
let activePointerId = null;
let lastPoint = null;
let strokeChanged = false;

function completeStitchAt(x, y) {
  if (
    x < 0 || x >= columns ||
    y < 0 || y >= rows
  ) {
    return;
  }

  const id = `${x}-${y}`;

  if (!validStitches.has(id) || completedStitches.has(id)) {
    return;
  }

  completedStitches.add(id);

  const index = y * columns + x;
  const stitch = gridElement.children[index];

  if (stitch) {
    stitch.classList.add("completed");
  }

  strokeChanged = true;
  updatePoem();
}



function getGridPoint(clientX, clientY) {
  const rect = gridElement.getBoundingClientRect();

  if (!rect.width || !rect.height) {
    return null;
  }

  const x = Math.floor(
    ((clientX - rect.left) / rect.width) * columns
  );

  const y = Math.floor(
    ((clientY - rect.top) / rect.height) * rows
  );

  return {
    x: Math.max(0, Math.min(columns - 1, x)),
    y: Math.max(0, Math.min(rows - 1, y))
  };
}


function stitchBetween(from, to) {
  const dx = to.x - from.x;
  const dy = to.y - from.y;

  const steps = Math.max(Math.abs(dx), Math.abs(dy));

  if (steps === 0) {
    completeStitchAt(to.x, to.y);
    return;
  }

  for (let i = 0; i <= steps; i++) {
    const x = Math.round(
      from.x + (dx * i) / steps
    );

    const y = Math.round(
      from.y + (dy * i) / steps
    );

    completeStitchAt(x, y);
  }
}


gridElement.addEventListener("pointerdown", event => {
  if (event.pointerType === "mouse" && event.button !== 0) {
    return;
  }

  if (isStitching) {
    return;
  }

  event.preventDefault();

  isStitching = true;
  activePointerId = event.pointerId;
  strokeChanged = false;

  gridElement.setPointerCapture(event.pointerId);

  const point = getGridPoint(event.clientX, event.clientY);

  if (point) {
    completeStitchAt(point.x, point.y);
    lastPoint = point;
  }
});


gridElement.addEventListener("pointermove", event => {
  if (!isStitching || event.pointerId !== activePointerId) {
    return;
  }

  if (event.pointerType === "mouse" && !(event.buttons & 1)) {
    finishStitching();
    return;
  }

  const point = getGridPoint(event.clientX, event.clientY);

  if (!point) {
    return;
  }

  if (lastPoint) {
    stitchBetween(lastPoint, point);
  } else {
    completeStitchAt(point.x, point.y);
  }

  lastPoint = point;
});



function finishStitching() {
  if (!isStitching) {
    return;
  }

  if (strokeChanged) {
    saveProgress();
  }

  isStitching = false;
  activePointerId = null;
  lastPoint = null;
  strokeChanged = false;
}

gridElement.addEventListener("pointerup", event => {
  if (event.pointerId === activePointerId) {
    const point = getGridPoint(event.clientX, event.clientY);

    if (point && lastPoint) {
      stitchBetween(lastPoint, point);
    }

    finishStitching();
  }
});

gridElement.addEventListener("pointercancel", event => {
  if (event.pointerId === activePointerId) {
    finishStitching();
  }
});

gridElement.addEventListener("lostpointercapture", () => {
  finishStitching();
});



function updatePoem() {
  const totalStitches = validStitches.size;

  const progress = totalStitches === 0
    ? 0
    : (completedStitches.size / totalStitches) * 100;

  const revealedLines =
    progress >= 80 ? 3 :
    progress >= 50 ? 2 :
    progress >= 20 ? 1 : 0;

  introduction.hidden = revealedLines > 0;
  haikuElement.hidden = revealedLines === 0;

  poemLines.forEach((line, index) => {
    if (index < revealedLines) {
      if (line.textContent !== pattern.haiku[index]) {
        line.textContent = pattern.haiku[index];

        line.classList.remove("revealed");
        void line.offsetWidth;
        line.classList.add("revealed");
      }
    } else {
      line.textContent = ". . . . . . . . . .";
      line.classList.remove("revealed");
    }
  });
}



function updatePagination() {
  document.getElementById("pattern-number").textContent =
    pattern.number;

  document.getElementById("page-count").textContent =
    `${String(page).padStart(2, "0")} / ${String(patterns.length).padStart(2, "0")}`;

  const newer = document.getElementById("newer-link");
  const older = document.getElementById("older-link");

  if (page === 1) {
    newer.classList.add("disabled");
    newer.removeAttribute("href");
  } else {
    newer.classList.remove("disabled");

    newer.href = page === 2
      ? "index.html"
      : `?page=${page - 1}`;
  }

  if (page === patterns.length) {
    older.classList.add("disabled");
    older.removeAttribute("href");
  } else {
    older.classList.remove("disabled");
    older.href = `?page=${page + 1}`;
  }
}



