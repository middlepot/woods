function createCross() {
  const svgNS = "http://www.w3.org/2000/svg";

  const svg = document.createElementNS(svgNS, "svg");

  svg.setAttribute("viewBox", "0 0 100 100");
  svg.setAttribute("preserveAspectRatio", "none");
  svg.setAttribute("aria-hidden", "true");

  svg.classList.add("stitch-cross");

  const firstLine = document.createElementNS(svgNS, "line");

  firstLine.setAttribute("x1", "20");
  firstLine.setAttribute("y1", "20");
  firstLine.setAttribute("x2", "80");
  firstLine.setAttribute("y2", "80");

  const secondLine = document.createElementNS(svgNS, "line");

  secondLine.setAttribute("x1", "80");
  secondLine.setAttribute("y1", "20");
  secondLine.setAttribute("x2", "20");
  secondLine.setAttribute("y2", "80");

  svg.appendChild(firstLine);
  svg.appendChild(secondLine);

  return svg;
}


function createEmbroidery() {
  gridElement.innerHTML = "";

  gridElement.style.gridTemplateColumns =
    `repeat(${columns}, minmax(0, 1fr))`;

  gridElement.style.gridTemplateRows =
    `repeat(${rows}, minmax(0, 1fr))`;

  const fragment = document.createDocumentFragment();

  pattern.grid.forEach((row, y) => {
    [...row].forEach((symbol, x) => {
      const stitch = document.createElement("div");
      const stitchId = `${x}-${y}`;

      stitch.className = "stitch";
      stitch.dataset.stitchId = stitchId;

      const fabricSquare = document.createElement("div");
      fabricSquare.className = "fabric-square";
      stitch.appendChild(fabricSquare);

      if (symbol === ".") {
        stitch.classList.add("empty");
      } else {
        stitch.style.setProperty(
          "--thread-color",
          pattern.colors[symbol]
        );

        const stitchColor = document.createElement("div");
        stitchColor.className = "stitch-color";
        stitch.appendChild(stitchColor);

        stitch.appendChild(createCross());

        if (completedStitches.has(stitchId)) {
          stitch.classList.add("completed");
        }
      }

      fragment.appendChild(stitch);
    });
  });

  gridElement.appendChild(fragment);
}



